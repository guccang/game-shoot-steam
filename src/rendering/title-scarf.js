// 固定左颈端点，沿布身逐渐增加重力下垂，速度升高时恢复片头迎风轮廓。
export function drawTitleScarf(c, time, lift, neckX, neckY, style) {
  const points = scarfFrames[Math.floor(time * 12) % scarfFrames.length];
  c.save();
  c.translate(neckX, neckY);
  c.beginPath();
  for (let i = 0; i < points.length * 2; i++) {
    const top = i < points.length;
    const [sourceX, upper, lower] = points[top ? i : points.length * 2 - i - 1];
    const distance = (320 - sourceX) / 43;
    const x = -distance * (11 + 24 * lift) * style.length;
    const y = ((top ? upper : lower) - 557) * 0.32 + distance * (12 - 25 * lift);
    if (i === 0) c.moveTo(x, y);
    else c.lineTo(x, y);
  }
  c.closePath();
  c.lineJoin = 'round';
  c.fillStyle = style.cloth;
  c.strokeStyle = style.edge;
  c.lineWidth = 1.6;
  c.fill(); c.stroke(); c.restore();
}
