// 共用美术绘制主体：颜色、线宽与局部细节来自当前风格配置。
import { style } from '../art-styles/config.js';
import { drawWorldSign } from './world-signs.js';
import { box, poly, oval } from './primitives.js';

// 工坊立面叠加在原营地小屋内，开放维修门与工具架在正常游戏尺寸仍可识别。

// 同一图集绘制入口服务昼夜缓存，不额外添加地板或遮挡投影。
// 共用绘制与动作输入，风格差异由配置提供。
export function drawWorkshopFacade(c, kind = true) {
  if (kind === 'vehicle') {
    // 载具工坊使用宽卷帘、吊架与备用轮，和武器台剪影分开。
    box(c, -49, -62, 94, 55, 3, '#365a47', '#795f3f', 2);
    for (let y = -60; y < -48; y += 6) box(c, -45, y, 86, 4, 1, '#9aaa84', '#56745b', 1);
    box(c, -42, -9, 82, 4, 1, style.workshopBuilding.drawWorkshopFacadeColor, '#315c43', 1.5);
    for (const x of [-45, 44]) {
      oval(c, x, -16, 7, 10, '#52645a', '#315c43', 2);
      oval(c, x, -16, 4, 6, '#c0c3ad');
    }
    box(c, 30, -48, 4, 27, 1, '#c0c3ad', '#315c43', 1);
    box(c, 15, -49, 20, 4, 1, '#c0c3ad', '#315c43', 1);
    box(c, -26, -86, 52, 16, 3, '#f4dca0', '#315c43', 1.5);
    oval(c, -8, -78, 5, 5, '#718672', '#315c43', 1);
    oval(c, 11, -78, 5, 5, '#718672', '#315c43', 1);
    box(c, -8, -81, 19, 3, 1, '#718672');
    return;
  }
  box(c, -48, -59, 68, 52, 3, '#315C43', '#795F3F', 2);
  box(c, -43, -54, 58, 45, 2, '#56745B', '#315C43', 1.5);
  box(c, -48, -65, 68, 11, 2, '#B68A51', '#315C43', 2);
  for (let x = -43; x < 18; x += 10) box(c, x, -64, 5, 9, 1, '#E0B777');
  box(c, -36, -28, 44, 6, 2, '#E0B777', '#315C43', 1.5);
  for (const x of [-32, 1]) box(c, x, -22, 4, 14, 1, '#B68A51', '#315C43', 1);
  oval(c, -21, -33, 9, 6, '#90A875', '#315C43', 1.5);
  box(c, -16, -38, 20, 5, 1, '#C0C3AD', '#315C43', 1);
  box(c, 30, -64, 22, 31, 2, '#E0B777', '#315C43', 1.5);
  for (const x of [35, 44]) {
    box(c, x, -55, 3, 16, 1, '#718672', '#315C43', 1);
    poly(
      c,
      [
        [x - 2, -60],
        [x, -56],
        [x + 4, -61],
        [x + 5, -54],
        [x - 3, -54],
      ],
      '#C0C3AD',
      '#315C43',
      1,
    );
  }
  box(c, -30, -86, 40, 16, 3, '#F4DCA0', '#315C43', 1.5);
  box(c, -21, -81, 23, 4, 1, '#718672', '#315C43', 1);
  box(c, -16, -77, 5, 6, 1, '#B68A51', '#315C43', 1);
  drawWorldSign(c, '武器工坊', 0, -6);
}
